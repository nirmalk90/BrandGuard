import { expect, test } from '@playwright/test'

test('artwork evidence and campaign links reopen the reviewed revision', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', {name: 'Try Live Demo'}).click()
  await page.getByLabel('Demo role').selectOption('admin')
  await page.getByRole('link', {name:'Settings'}).click()
  const images = await page.evaluate(() => {
    const ref = document.createElement('canvas')
    ref.width = 80; ref.height = 60
    const mark = ref.getContext('2d')!
    mark.fillStyle = '#fff'; mark.fillRect(0,0,80,60)
    mark.fillStyle = '#3de0c2'; mark.fillRect(6,6,64,46)
    mark.fillStyle = '#18323f'; mark.font = 'bold 32px sans-serif'; mark.fillText('N',20,42)
    const art = document.createElement('canvas')
    art.width = 640; art.height = 240
    const ctx = art.getContext('2d')!
    ctx.fillStyle = 'white'; ctx.fillRect(0,0,640,240)
    ctx.drawImage(ref,20,20)
    ctx.fillStyle = '#e92342'; ctx.fillRect(500,0,140,240)
    ctx.fillStyle = '#18202f'; ctx.font = 'bold 38px Arial'; ctx.fillText('guaranteed results',20,175)
    return [ref,art].map(image => image.toDataURL('image/png').split(',')[1])
  })
  const imageFile = (name: string, base64: string) => ({ name, mimeType:'image/png', buffer:Buffer.from(base64,'base64') })
  await page.getByLabel('Add approved logo').setInputFiles(imageFile('mark.png', images[0]))
  await expect(page.getByText('mark.png')).toBeVisible()
  await page.getByLabel('Demo role').selectOption('creator')
  await page.getByRole('link', {name:'Content Review'}).click()
  await page.getByLabel('Content title').fill('Artwork launch')
  await page.getByLabel('Campaign', {exact:true}).fill('Summer launch')
  await page.getByLabel('Original content').fill('')
  await page.getByLabel('Attach artwork').setInputFiles(imageFile('poster.png', images[1]))
  await expect(page.getByText('poster.png', {exact:true})).toBeVisible()
  await page.getByRole('button', {name:'Analyze Content'}).click()
  await expect(page.getByRole('heading', {name:'Reviewed artwork'})).toBeVisible()
  await expect(page.locator('article.issue').filter({hasText:'Results guarantees'})).toContainText('guaranteed results')
  await page.getByLabel('Highlighted region').selectOption({label: await page.getByLabel('Highlighted region')
    .locator('option').filter({hasText:'guaranteed results'}).innerText()})
  await expect(page.locator('.art-box').first()).toBeVisible()
  await page.getByRole('button', {name:'Remove artwork'}).click()
  await page.getByLabel('Editable draft').fill('Ready for launch.')
  await page.getByRole('button', {name:'Re-run analysis'}).click()
  await expect(page.getByRole('heading', {name:'No issues detected'})).toBeVisible()
  await page.getByRole('link', {name:'Campaign governance'}).click()
  await expect(page.getByLabel('Campaign', {exact:true})).toHaveValue('Summer launch')
  const row = page.getByRole('row').filter({hasText:'Results guarantees'})
  await row.locator('summary').click()
  await row.getByRole('link', {name:'Artwork launch · v1'}).click()
  await expect(page.getByLabel('Version', {exact:true}).locator('option:checked')).toHaveText('Version 1')
  await expect(page.getByRole('heading', {name:'Reviewed artwork'})).toBeVisible()
  await expect(page.getByLabel('Editable draft')).toHaveCount(0)
})
