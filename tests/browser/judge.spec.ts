import { expect, test } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

test('judge reviews, revises, approves and reloads the NovaTech demo', async ({ page }) => {
  const screenshots = process.env.BRANDGUARD_SCREENSHOTS === '1'
  if (screenshots) await mkdir('docs/screenshots', { recursive: true })
  const capture = async (name: string) => {
    if (!screenshots) return
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({ path: 'docs/screenshots/' + name + '.png', animations: 'disabled', fullPage: true })
  }
  await page.goto('/')
  await page.getByRole('button', { name: 'Try Live Demo' }).click()
  await expect(page.getByRole('heading', { name: 'Workspace overview' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'No content reviewed yet' })).toBeVisible()
  await capture('workspace')
  await page.getByRole('link', { name: 'Brand Knowledge' }).click()
  await expect(page.getByRole('heading', { name: 'Starting subscription price' })).toBeVisible()
  await page.getByRole('link', { name: 'Content Review' }).click()
  await page.getByLabel('Original content').fill('   ')
  await page.getByRole('button', { name: 'Analyze Content' }).click()
  await expect(page.getByRole('alert')).toContainText('Enter or import content')
  await page.getByRole('button', { name: 'Restore sample' }).click()
  await page.getByRole('button', { name: 'Analyze Content' }).click()
  await expect(page.getByRole('heading', { name: 'Findings & evidence' })).toBeVisible()
  await expect(page.locator('article.issue')).toHaveCount(4)
  await expect(page.getByText('Contradicted', { exact: true })).toHaveCount(2)
  await page.getByText('Starting subscription price · rule v1', { exact: true }).click()
  await expect(page.getByText('NovaTech Product Fact Sheet', { exact: true })).toBeVisible()
  await capture('findings')
  await page.locator('article.issue').filter({ hasText: 'AI product terminology' }).getByRole('button', { name: 'Apply to draft' }).click()
  await expect(page.getByLabel('Editable draft')).toHaveValue(/AI-powered solution/)
  await page.getByLabel('Editable draft').fill('Explore our AI-powered solution. NovaTech subscription plans start at ₹499 per month.')
  await page.getByRole('button', { name: 'Re-run analysis' }).click()
  await expect(page.getByRole('heading', { name: 'No issues detected' })).toBeVisible()
  await page.getByRole('button', { name: 'Submit for approval' }).click()
  await expect(page.getByRole('status')).toContainText('Revision sent for approval')
  await page.getByLabel('Demo role').selectOption('reviewer')
  await page.getByRole('link', { name: 'Approval Queue' }).click()
  await page.getByRole('button', { name: 'NovaTech launch copy' }).click()
  await page.getByLabel('Decision rationale').fill('The revised copy uses approved terminology and the current subscription price.')
  await page.getByRole('button', { name: 'Approve', exact: true }).click()
  await expect(page.getByText('Decision saved.')).toBeVisible()
  await page.getByRole('link', { name: 'Review History' }).click()
  await expect(page.getByRole('row').filter({ hasText: 'NovaTech launch copy' })).toContainText('Approved')
  await page.getByRole('button', { name: 'NovaTech launch copy' }).click()
  await page.reload()
  await expect(page.getByText('The revised copy uses approved terminology and the current subscription price.')).toBeVisible()
  await expect(page.getByText('Jordan Rao').last()).toBeVisible()
  await capture('approval')
  await page.getByRole('combobox', { name: 'Version', exact: true }).selectOption({ label: 'Version 1' })
  await expect(page.locator('article.issue')).toHaveCount(4)
  await page.getByRole('link', { name: 'Analytics' }).click()
  await expect(page.getByRole('heading', { name: 'Most frequently flagged rules' })).toBeVisible()
  await expect(page.getByText('Starting subscription price', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Settings' }).click()
  await expect(page.getByRole('heading', { name: 'Brand profile' })).toBeVisible()
})

test('mobile navigation and admin rule creation feed a real review', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Try Live Demo' }).click()
  await page.getByLabel('Demo role').selectOption('admin')
  const openNav = page.getByRole('button', { name: 'Open navigation' })
  const closeNav = page.getByRole('button', { name: 'Close navigation' })
  await expect(page.getByRole('link', { name: 'Brand Knowledge' })).toHaveCount(0)
  await openNav.focus()
  await page.keyboard.press('Enter')
  await expect(closeNav).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('link', { name: 'Settings' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(openNav).toBeFocused()
  await page.keyboard.press('Enter')
  await page.getByRole('link', { name: 'Brand Knowledge' }).click()
  await expect(openNav).toHaveAttribute('aria-expanded', 'false')
  await page.getByRole('button', { name: 'Add rule' }).click()
  await page.getByLabel('Rule title').fill('Quantum promise policy')
  await page.getByLabel('Description', { exact: true }).fill('Use approved names for the productivity suite.')
  await page.getByLabel('Phrase to check').fill('quantum promise')
  await page.getByRole('button', { name: 'Save rule' }).click()
  await expect(page.getByRole('heading', { name: 'Quantum promise policy' })).toBeVisible()
  await page.getByLabel('Demo role').selectOption('creator')
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('link', { name: 'Content Review' }).click()
  await page.getByLabel('Original content').fill('Try our quantum promise today.')
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Awaiting analysis' })).toBeVisible()
  await page.getByRole('button', { name: 'Analyze Content' }).click()
  await expect(page.getByText('Quantum promise policy · rule v1', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})
